/**
 * 제피가 지금 상황에 맞춰 건네는 말을 만든다.
 *
 * @param state 게임 상태
 * @returns 대사 목록
 */
export function zepiLines(state) {
  const lines = zepiBase(state);
  if (state.coins >= 10 && !state.gear.plan) {
    lines.push(say("제피", "코인이 모였네! 도서관의 계획 모드는 큰 일에 꼭 필요해. 한번 들러 봐."));
  }
  return lines;
}

function zepiBase(state) {
  if (state.trust < GATE_TRUST) {
    return [
      say("제피", `동쪽 길은 경비 로봇이 막고 있어. 신뢰를 ${GATE_TRUST} 쌓으면 비켜 줄 거야.`),
      say("제피", "길가의 민수에게 먼저 말을 걸어 봐. 사람이 직접 부탁하는 의뢰는 신뢰와 코인을 많이 줘! 이 대리의 일은 커서 준비가 필요해."),
    ];
  }
  if (state.trust < BOSS_TRUST) {
    return [
      say("제피", `작업장의 팀장 박은 신뢰가 ${BOSS_TRUST} 이상이어야 만나 준대.`),
      say("제피", "도서관에서 스킬과 CLAUDE.md를, 훅 대장간에서 훅을 챙겨 가. 위험한 의뢰가 많거든."),
      say("제피", "사용량이 바닥나면 쉼터로, 컨텍스트가 가득 차면 정리소로 가는 것도 잊지 마!"),
    ];
  }
  return [
    say("제피", "신뢰가 충분해! 작업장에서 팀장 박이 기다려."),
    say("제피", "들어가기 전에 쉼터에서 사용량을 채우고, 정리소에서 컨텍스트를 비워 두는 게 좋아."),
    say("제피", "팀장 박의 뱃지를 받으면 동쪽 숲지기가 레거시 숲을 열어 준대. 숲에도 관장이 있대!"),
  ];
}

/**
 * 경비 로봇의 대사를 만든다.
 *
 * @param state 게임 상태
 * @returns 대사 목록
 */
export function guardLines(state) {
  if (state.trust < GATE_TRUST) {
    return [
      say("경비 로봇", `삐빅. 신뢰 ${GATE_TRUST} 미만은 통행할 수 없습니다. (현재 ${state.trust})`),
      say("경비 로봇", "처음 보는 에이전트는 믿을 수 없습니다. 일로 증명하십시오."),
    ];
  }
  return [say("경비 로봇", "삐빅. 신뢰 확인 완료. 통과하십시오.")];
}

